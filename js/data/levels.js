// Pads or trims rows so a small typo in a map can't break the game.
export function normalizeMap(rows) {
  const w = Math.max(...rows.map((r) => r.length));
  return rows.map((row) => {
    if (row.length < w) return row.slice(0, -1).padEnd(w - 1, row.slice(-2, -1) || 'R') + 'R';
    return row;
  });
}
